export function translate(lang: Lang, text: string): string {
  return lang === 'hi' ? (HI[text] ?? text) : text;
}

type Value = { lang: Lang; t(text: string): string; setLang(lang: Lang): void };
const Context = createContext<Value>({ lang: 'hi', t: text => translate('hi', text), setLang() {} });

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('hi');
  useEffect(() => { getSetting(LANGUAGE_SETTING).then(value => { if (value === 'en' || value === 'hi') setLangState(value); }); }, []);
  const setLang = useCallback((next: Lang) => { setLangState(next); setSetting(LANGUAGE_SETTING, next).catch(() => {}); }, []);
  const t = useCallback((text: string) => translate(lang, text), [lang]);
  return <Context.Provider value={{ lang, t, setLang }}>{children}</Context.Provider>;
}

export function useLanguage(): Value { return useContext(Context); }
